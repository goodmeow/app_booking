// These databases belong to the legacy/reconstruction/parity work. None of them
// may ever receive an import or a pre-flight write.
export const FORBIDDEN_DATABASE_NAMES = [
  "bjb",
  "bjb_compare",
  "360booking_reconstruction_test",
  "360booking_parity_test",
];

// Databases the restore/copy helpers treat as disposable even though they are
// not part of FORBIDDEN_DATABASE_NAMES.
export const DISPOSABLE_DATABASE_PATTERN = /(_test|_check|_scratch)$/i;

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const EMPLOYEE_ID_PATTERN = /^[A-Za-z0-9._-]{1,40}$/;
const PLAN_ACTIONS = new Set(["update", "create"]);
const CARD_ACTIONS = new Set(["existing", "keep-existing", "no-card", "replace", "add"]);
const PASSWORD_ACTIONS = new Set(["set-default"]);
const SPECIAL_ROLES = new Set(["admin", "receptionist"]);
const CARD_NUMBER_PATTERN = /^[A-Za-z0-9._-]{1,64}$/;

export class FatalError extends Error {
  constructor(message) {
    super(message);
    this.name = "FatalError";
  }
}

export const isForbiddenDatabase = (name) =>
  FORBIDDEN_DATABASE_NAMES.includes(
    String(name ?? "")
      .trim()
      .toLowerCase(),
  );

export const assertDatabaseNameAllowed = (name, { databaseRole = "target" } = {}) => {
  const normalized = String(name ?? "").trim();
  if (!normalized) throw new FatalError("Database name is empty");
  if (isForbiddenDatabase(normalized)) {
    throw new FatalError(
      `Refusing to use ${databaseRole} database "${normalized}": it belongs to the legacy/parity set`,
    );
  }
  return normalized;
};

export const normalizeEmail = (value) =>
  String(value ?? "")
    .trim()
    .toLowerCase();
export const normalizeEmployeeId = (value) =>
  String(value ?? "")
    .trim()
    .toLowerCase();
export const normalizeCardNumber = (value) => String(value ?? "").trim();

// Console and report output keep the domain so an operator can still tell the
// companies apart, but never the full local part.
export const maskEmail = (value) => {
  const email = String(value ?? "").trim();
  const at = email.lastIndexOf("@");
  if (at <= 0) return "***";
  const local = email.slice(0, at);
  const domain = email.slice(at + 1);
  const visible = local.slice(0, 1);
  return `${visible}***@${domain}`;
};

export const maskCardNumber = (value) => {
  const card = String(value ?? "").trim();
  if (card.length <= 4) return "****";
  return `****${card.slice(-4)}`;
};

export const passwordByteLength = (value) => Buffer.byteLength(String(value ?? ""), "utf8");

export const validateDefaultPassword = (value) => {
  const password = String(value ?? "");
  if (!password) throw new FatalError("DEFAULT_PASSWORD is missing");
  const bytes = passwordByteLength(password);
  if (bytes < 8 || bytes > 72) {
    throw new FatalError(`DEFAULT_PASSWORD must be 8-72 bytes, got ${bytes}`);
  }
  return password;
};

// Minimal RFC4180 reader. The plan files are generated by Python's csv module,
// so quoted fields and CRLF line endings both have to work.
export const parseCsv = (text) => {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  let index = 0;

  const pushField = () => {
    row.push(field);
    field = "";
  };

  while (index < text.length) {
    const character = text[index];

    if (inQuotes) {
      if (character === '"') {
        if (text[index + 1] === '"') {
          field += '"';
          index += 2;
          continue;
        }
        inQuotes = false;
        index += 1;
        continue;
      }
      field += character;
      index += 1;
      continue;
    }

    if (character === '"') {
      inQuotes = true;
      index += 1;
      continue;
    }
    if (character === ",") {
      pushField();
      index += 1;
      continue;
    }
    if (character === "\r") {
      index += 1;
      continue;
    }
    if (character === "\n") {
      pushField();
      rows.push(row);
      row = [];
      index += 1;
      continue;
    }

    field += character;
    index += 1;
  }

  if (inQuotes) throw new FatalError("CSV ends inside a quoted field");
  if (field !== "" || row.length > 0) {
    pushField();
    rows.push(row);
  }
  return rows;
};

export const readCsvRecords = async (filePath) => {
  const text = (await readFile(filePath, "utf8")).replace(/^\uFEFF/, "");
  const [headerRow, ...dataRows] = parseCsv(text);
  if (!headerRow) throw new FatalError(`${filePath} is empty`);
  const header = headerRow.map((name) => name.trim());

  return dataRows
    .filter((row) => row.some((cell) => String(cell).trim() !== ""))
    .map((row, rowIndex) => {
      const record = { rowNumber: rowIndex + 2 };
      header.forEach((name, columnIndex) => {
        record[name] = String(row[columnIndex] ?? "").trim();
      });
      return record;
    });
};

const assertHeaders = (records, filePath, requiredHeaders) => {
  if (records.length === 0) throw new FatalError(`${filePath} has no data rows`);
  const missing = requiredHeaders.filter((header) => !Object.hasOwn(records[0], header));
  if (missing.length > 0) {
    throw new FatalError(`${filePath} is missing columns: ${missing.join(", ")}`);
  }
};

// Reads KEY=VALUE env files without a dependency. Quotes are optional and
// comments start with '#'; nothing is exported into process.env.
export const readEnvFile = async (filePath) => {
  const text = await readFile(filePath, "utf8");
  const values = {};

  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const separator = line.indexOf("=");
    if (separator <= 0) continue;
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
};

export const readDefaultPassword = async (defaultsPath) => {
  const values = await readEnvFile(defaultsPath);
  return validateDefaultPassword(values.DEFAULT_PASSWORD);
};

export const readImportPlan = async (filePath) => {
  const records = await readCsvRecords(filePath);
  assertHeaders(records, filePath, [
    "action",
    "employee_id",
    "name",
    "email_to_use",
    "floor",
    "source",
    "placeholder",
    "card_number",
    "card_action",
  ]);

  const rows = records.map((record) => {
    const action = record.action.toLowerCase();
    if (!PLAN_ACTIONS.has(action)) {
      throw new FatalError(`Row ${record.rowNumber}: unknown action "${record.action}"`);
    }
    const employeeId = record.employee_id.trim();
    if (!employeeId) throw new FatalError(`Row ${record.rowNumber}: employee_id is empty`);
    if (!EMPLOYEE_ID_PATTERN.test(employeeId)) {
      throw new FatalError(`Row ${record.rowNumber}: employee_id "${employeeId}" has an unsupported format`);
    }
    const email = record.email_to_use.trim();
    if (!EMAIL_PATTERN.test(email)) {
      throw new FatalError(`Row ${record.rowNumber}: email_to_use is not a valid address`);
    }
    const floor = record.floor.trim();
    if (!floor) throw new FatalError(`Row ${record.rowNumber}: floor is empty`);

    const cardAction = (record.card_action || "no-card").toLowerCase();
    if (!CARD_ACTIONS.has(cardAction)) {
      throw new FatalError(`Row ${record.rowNumber}: unknown card_action "${record.card_action}"`);
    }

    const cardNumber = normalizeCardNumber(record.card_number);
    if ((cardAction === "add" || cardAction === "replace") && !cardNumber) {
      throw new FatalError(`Row ${record.rowNumber}: card_action "${cardAction}" needs a card_number`);
    }

    return {
      rowNumber: record.rowNumber,
      action,
      employeeId,
      name: record.name,
      email,
      floor,
      department: record.department ?? "",
      source: record.source,
      placeholder: record.placeholder.toLowerCase() === "yes",
      cardNumber,
      cardAction,
      oldCardNumber: normalizeCardNumber(record.old_bjb_card),
      oldCardAction: (record.old_card_action ?? "").toLowerCase(),
      mustChangePassword: (record.must_change_password ?? "").toLowerCase() === "yes",
    };
  });

  return rows;
};

// A clean-slate plan contains only creates. The explicit --fresh flag is still
// available, but detecting this shape keeps a forgotten flag from running the
// legacy update path.
export const detectFreshPlan = (planRows) => planRows.length > 0 && planRows.every((row) => row.action === "create");

export const readPasswordResetPlan = async (filePath) => {
  const records = await readCsvRecords(filePath);
  assertHeaders(records, filePath, ["employee_id", "name", "email", "source", "password_action"]);

  return records.map((record) => {
    const email = record.email.trim();
    if (!EMAIL_PATTERN.test(email)) {
      throw new FatalError(`Row ${record.rowNumber}: email is not a valid address`);
    }
    const passwordAction = record.password_action.toLowerCase();
    if (!PASSWORD_ACTIONS.has(passwordAction)) {
      throw new FatalError(`Row ${record.rowNumber}: unknown password_action "${record.password_action}"`);
    }
    return {
      rowNumber: record.rowNumber,
      employeeId: record.employee_id.trim(),
      name: record.name,
      email,
      source: record.source,
      passwordAction,
      mustChangePassword: (record.must_change_password ?? "").toLowerCase() === "yes",
    };
  });
};

export const readCardChangePlan = async (filePath) => {
  const records = await readCsvRecords(filePath);
  assertHeaders(records, filePath, [
    "employee_id",
    "email",
    "old_bjb_card",
    "new_cvsecurity_card",
    "old_card_action",
    "new_card_action",
  ]);

  return records.map((record) => {
    const email = record.email.trim();
    if (!EMAIL_PATTERN.test(email)) {
      throw new FatalError(`Row ${record.rowNumber}: email is not a valid address`);
    }
    const oldCardNumber = normalizeCardNumber(record.old_bjb_card);
    const newCardNumber = normalizeCardNumber(record.new_cvsecurity_card);
    if (!newCardNumber) {
      throw new FatalError(`Row ${record.rowNumber}: new_cvsecurity_card is empty`);
    }
    if (oldCardNumber && oldCardNumber === newCardNumber) {
      throw new FatalError(`Row ${record.rowNumber}: old and new card are identical`);
    }
    return {
      rowNumber: record.rowNumber,
      employeeId: record.employee_id.trim(),
      name: record.name,
      email,
      floor: (record.floor ?? "").trim(),
      oldCardNumber,
      newCardNumber,
      oldCardAction: (record.old_card_action ?? "").toLowerCase(),
      newCardAction: (record.new_card_action ?? "").toLowerCase(),
      source: record.card_source ?? "",
    };
  });
};

// Rooms are accounts with type 'room' in tbl_users. The email is the room
// identity used by the kiosk, so it must be short and unique.
export const readRoomPlan = async (filePath) => {
  const records = await readCsvRecords(filePath);
  assertHeaders(records, filePath, [
    "name",
    "email",
    "floor",
    "capacity",
    "building",
    "feature",
    "password_action",
    "must_change_password",
  ]);

  return records.map((record) => {
    const name = record.name.trim();
    const email = record.email.trim();
    const floor = record.floor.trim();

    if (!name) throw new FatalError(`Room row ${record.rowNumber}: name is empty`);
    if (!EMAIL_PATTERN.test(email)) {
      throw new FatalError(`Room row ${record.rowNumber}: email is not a valid address`);
    }
    if (!floor) throw new FatalError(`Room row ${record.rowNumber}: floor is empty`);
    if ((record.password_action ?? "").toLowerCase() !== "set-default") {
      throw new FatalError(`Room row ${record.rowNumber}: only password_action=set-default is supported`);
    }

    return {
      rowNumber: record.rowNumber,
      name,
      email,
      floor,
      capacity: record.capacity.trim(),
      building: record.building.trim(),
      feature: record.feature.trim(),
      mustChangePassword: (record.must_change_password ?? "").toLowerCase() === "yes",
    };
  });
};

// Admin/receptionist accounts used by the tablet and the front desk. They are
// employees, not rooms, and must carry the role the CMS expects.
export const readSpecialUserPlan = async (filePath) => {
  const records = await readCsvRecords(filePath);
  assertHeaders(records, filePath, [
    "name",
    "email",
    "employee_id",
    "role",
    "floor",
    "must_change_password",
    "password_action",
  ]);

  return records.map((record) => {
    const name = record.name.trim();
    const email = record.email.trim();
    const employeeId = record.employee_id.trim();
    const role = record.role.trim().toLowerCase();
    const floor = record.floor.trim();

    if (!name) throw new FatalError(`Special user row ${record.rowNumber}: name is empty`);
    if (!EMAIL_PATTERN.test(email)) {
      throw new FatalError(`Special user row ${record.rowNumber}: email is not a valid address`);
    }
    if (!EMPLOYEE_ID_PATTERN.test(employeeId)) {
      throw new FatalError(`Special user row ${record.rowNumber}: employee_id has an unsupported format`);
    }
    if (!SPECIAL_ROLES.has(role)) {
      throw new FatalError(`Special user row ${record.rowNumber}: role must be admin or receptionist`);
    }
    if (role === "receptionist" && !floor) {
      throw new FatalError(`Special user row ${record.rowNumber}: receptionists need a floor`);
    }
    if ((record.password_action ?? "").toLowerCase() !== "set-default") {
      throw new FatalError(`Special user row ${record.rowNumber}: only password_action=set-default is supported`);
    }

    return {
      rowNumber: record.rowNumber,
      name,
      email,
      employeeId,
      role,
      floor,
      mustChangePassword: (record.must_change_password ?? "").toLowerCase() === "yes",
    };
  });
};

export const readMasterCardPlan = async (filePath) => {
  const records = await readCsvRecords(filePath);
  assertHeaders(records, filePath, ["card_number"]);

  const seen = new Set();
  return records.map((record) => {
    const cardNumber = normalizeCardNumber(record.card_number);
    if (!CARD_NUMBER_PATTERN.test(cardNumber)) {
      throw new FatalError(`Master card row ${record.rowNumber}: card_number has an unsupported format`);
    }
    const key = cardNumber.toLowerCase();
    if (seen.has(key)) {
      throw new FatalError(`Master card row ${record.rowNumber}: duplicate card number in the file`);
    }
    seen.add(key);
    return { rowNumber: record.rowNumber, cardNumber };
  });
};

// Card changes exist in two files: the focused replace list (old + new card)
// and the main plan (replace/add rows). The focused list wins, then the plan
// adds the one "add" row that is not a replacement.
export const buildCardItems = (planRows, cardChangeRows) => {
  const items = [];
  const seen = new Set();
  const itemKey = (employeeId, newCardNumber) =>
    `${normalizeEmployeeId(employeeId)}|${normalizeCardNumber(newCardNumber).toLowerCase()}`;

  for (const row of cardChangeRows) {
    const key = itemKey(row.employeeId, row.newCardNumber);
    if (seen.has(key)) continue;
    seen.add(key);
    items.push({
      rowNumber: row.rowNumber,
      employeeId: row.employeeId,
      email: row.email,
      action: "replace",
      oldCardNumber: row.oldCardNumber,
      newCardNumber: row.newCardNumber,
      origin: "plan-card-changes",
    });
  }

  for (const row of planRows) {
    if (row.cardAction !== "replace" && row.cardAction !== "add") continue;
    const key = itemKey(row.employeeId, row.cardNumber);
    if (seen.has(key)) continue;
    seen.add(key);
    items.push({
      rowNumber: row.rowNumber,
      employeeId: row.employeeId,
      email: row.email,
      action: row.cardAction,
      oldCardNumber: row.oldCardNumber,
      newCardNumber: row.cardNumber,
      origin: "plan-import",
    });
  }

  return items;
};

// Applied by both the user importer and the asset importer. The target must be
// named explicitly and must never be one of the legacy/parity databases.
export const assertApplyTarget = (databaseName) => {
  const allowedTarget = String(process.env.IMPORT_TARGET_DB ?? "").trim();
  if (!allowedTarget) {
    throw new FatalError(
      "--apply requires IMPORT_TARGET_DB (for example IMPORT_TARGET_DB=360booking). " +
        "Dry-run is the default and does not need it.",
    );
  }
  if (isForbiddenDatabase(allowedTarget)) {
    throw new FatalError(`IMPORT_TARGET_DB="${allowedTarget}" is a forbidden legacy database`);
  }
  if (databaseName !== allowedTarget) {
    throw new FatalError(
      `Connected database "${databaseName}" is not the explicit IMPORT_TARGET_DB ` +
        `"${allowedTarget}". Refusing to write.`,
    );
  }
};

// Writing is allowed only after the operator proves a dump exists. A custom
// format pg_dump archive starts with the ASCII marker "PGDMP", which rejects
// empty placeholders and copied text files.
export const assertBackupProof = async (backupFileOption) => {
  if (process.env.BACKUP_CONFIRMED === "1") return "BACKUP_CONFIRMED=1";

  const backupFile = backupFileOption || process.env.BACKUP_FILE;
  if (!backupFile) {
    throw new FatalError(
      "--apply needs backup proof: set BACKUP_CONFIRMED=1 after taking a dump, " +
        "or pass --backup-file=PATH with a non-empty dump.",
    );
  }

  const info = await stat(backupFile).catch(() => null);
  if (!info || !info.isFile() || info.size === 0) {
    throw new FatalError(`Backup file "${backupFile}" does not exist or is empty`);
  }

  const handle = await open(backupFile, "r");
  try {
    const buffer = Buffer.alloc(5);
    await handle.read(buffer, 0, 5, 0);
    if (buffer.toString("ascii") !== "PGDMP") {
      throw new FatalError(`Backup file "${backupFile}" is not a pg_dump custom-format archive`);
    }
  } finally {
    await handle.close();
  }

  return backupFile;
};

// --key=value and --flag parser. Unknown names fail loudly instead of being
// silently ignored, which matters for destructive flags like --apply.
export const parseOptions = (argv, spec) => {
  const options = {};

  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];

    if (token === "--help" || token === "-h") {
      options.help = true;
      continue;
    }
    if (!token.startsWith("--")) {
      throw new FatalError(`Unknown positional argument: ${token}`);
    }

    const separator = token.indexOf("=");
    const name = separator === -1 ? token.slice(2) : token.slice(2, separator);
    const inlineValue = separator === -1 ? undefined : token.slice(separator + 1);
    const kind = spec[name];

    if (!kind) throw new FatalError(`Unknown option: --${name}`);

    if (kind === "flag") {
      if (inlineValue !== undefined) throw new FatalError(`--${name} does not take a value`);
      options[name] = true;
      continue;
    }

    const value = inlineValue ?? argv[index + 1];
    if (value === undefined || value === "" || value.startsWith("--")) {
      throw new FatalError(`--${name} needs a value`);
    }
    if (inlineValue === undefined) index += 1;
    options[name] = value;
  }

  return options;
};

export const csvEscape = (value) => {
  const text = String(value ?? "");
  if (/[",\r\n]/.test(text)) return `"${text.replaceAll('"', '""')}"`;
  return text;
};

export const writeCsvReport = (rows, columns) => {
  const lines = [columns.join(",")];
  for (const row of rows) {
    lines.push(columns.map((column) => csvEscape(row[column])).join(","));
  }
  return `${lines.join("\n")}\n`;
};
