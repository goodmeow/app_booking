// Shared readers for the BJB -> 360 Scheduler import kit.
//
// The plan files contain PII and stay outside the repository
// (`integration/*.local.csv`). This module only parses and validates them; it
// never writes to the database and never prints full e-mail addresses, card
// numbers, or passwords.

